CREATE TABLE IF NOT EXISTS public.audio_fingerprints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash bigint NOT NULL,
    movie_id text NOT NULL REFERENCES public.movies (id) ON DELETE CASCADE,
    timestamp_ms bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS audio_fingerprints_movie_id_idx
    ON public.audio_fingerprints (movie_id);

CREATE INDEX IF NOT EXISTS audio_fingerprints_hash_idx
    ON public.audio_fingerprints (hash);

ALTER TABLE public.audio_fingerprints ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.audio_fingerprints FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.audio_fingerprints TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION public.match_audio_candidates(
    query_hashes bigint[]
)
RETURNS TABLE (
    hash bigint,
    movie_id text,
    timestamp_ms bigint
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $function$
    SELECT fingerprint.hash, fingerprint.movie_id, fingerprint.timestamp_ms
    FROM public.audio_fingerprints AS fingerprint
    WHERE fingerprint.hash = ANY (query_hashes);
$function$;

REVOKE ALL ON FUNCTION public.match_audio_candidates(bigint[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.match_audio_candidates(bigint[]) TO service_role;
