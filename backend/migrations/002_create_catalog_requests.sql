CREATE TABLE IF NOT EXISTS public.catalog_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id bigint NOT NULL,
    title text NOT NULL,
    release_date text,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'reviewed', 'added', 'declined')),
    submitted_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.catalog_requests ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.catalog_requests
    FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.catalog_requests TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.catalog_requests_id_seq TO service_role;
