CREATE TABLE IF NOT EXISTS public.movies (
    id text PRIMARY KEY,
    tmdb_id bigint UNIQUE,
    title text,
    release_date text,
    poster_path text,
    backdrop_path text,
    overview text,
    runtime integer,
    genres jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.fingerprints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash bigint NOT NULL,
    movie_id text NOT NULL REFERENCES public.movies (id) ON DELETE CASCADE,
    timestamp_ms bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS fingerprints_movie_id_idx
    ON public.fingerprints (movie_id);

ALTER TABLE public.movies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fingerprints ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.movies FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.fingerprints FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.movies TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.fingerprints TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION public.match_fingerprint_candidates(
    query_hashes bigint[],
    distance_threshold integer
)
RETURNS TABLE (
    hash bigint,
    movie_id text,
    timestamp_ms bigint
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $function$
    SELECT fingerprint.hash, fingerprint.movie_id, fingerprint.timestamp_ms
    FROM public.fingerprints AS fingerprint
    CROSS JOIN unnest(query_hashes) AS query(hash)
    WHERE bit_count((fingerprint.hash # query.hash)::bit(64)) <= distance_threshold;
$function$;

REVOKE ALL ON FUNCTION public.match_fingerprint_candidates(bigint[], integer)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.match_fingerprint_candidates(bigint[], integer)
    TO service_role;
